const RTL_LANGS = new Set(['ar']);
const SUPPORTED_LANGS = ['fr', 'en', 'ar'];
const LANG_STORAGE_KEY = 'dzair-carosse_lang';

function getLang() {
  const stored = localStorage.getItem(LANG_STORAGE_KEY);
  if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  // Défaut : langue du navigateur si supportée, sinon français.
  const nav = (navigator.language || 'fr').slice(0, 2);
  return SUPPORTED_LANGS.includes(nav) ? nav : 'fr';
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
  applyDocumentDir(lang);
}

function isRtl(lang) { return RTL_LANGS.has(lang); }

function applyDocumentDir(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl(lang) ? 'rtl' : 'ltr';
}

// t('key', {var: 'valeur'}) -> traduction avec interpolation de {var}.
// Si la clé est absente dans la langue active, on retombe sur le français
// puis, en dernier recours, sur la clé elle-même (jamais d'écran cassé).
function t(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) ?? I18N.fr[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
    }
  }
  return str;
}

// Pluriel simplifié pour FR/EN (ajout d'un "s"), forme unique pour l'arabe
// (l'accord pluriel arabe dépend du nombre exact — duel/pluriel/pluriel de
// petit nombre — ce qui dépasse le cadre d'un compteur d'interface ; on
// utilise volontairement une forme neutre plutôt qu'un accord incorrect).
function plural(n, key) {
  const lang = getLang();
  const label = t(key);
  if (lang === 'ar') return label;
  return label + (n > 1 ? 's' : '');
}
